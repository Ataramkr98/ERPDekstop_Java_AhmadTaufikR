package com.erp.shared;

import java.lang.reflect.Field;
import java.util.Set;
import com.erp.config.CurrentUser;

/** Shared access and document lifecycle rules, used by REST and metadata. */
public final class RecordPolicy {
    private RecordPolicy() {}
    private static final Set<String> GENERATED = Set.of("AuditLog", "InvStock", "InvMovement", "JournalEntry", "JournalLine", "PurThreeWayMatch");
    private static final Set<String> ADMIN = Set.of("Company", "AppUser", "UserRole", "Role", "Permission", "SystemConfig", "NumberRange", "AuditLog");
    private static final Set<String> DEMO_SECURITY = Set.of("Company", "AppUser", "UserRole", "Role", "Permission", "SystemConfig");
    private static final Set<String> INTERNAL = Set.of("id", "companyId", "version", "createdAt", "createdBy", "updatedAt", "updatedBy", "active");
    private static final Set<String> SECRETS = Set.of("passwordHash", "password", "failedLoginCount", "lockedUntil", "lastLoginAt", "mustChangePassword");
    private static final Set<String> CALCULATED = Set.of("journalEntryId", "paidAmount", "balanceAmount", "currentBalance");
    public static boolean sensitive(String name) { return SECRETS.contains(name); }
    public static boolean writable(Field field) { return !INTERNAL.contains(field.getName()) && !sensitive(field.getName()) && !CALCULATED.contains(field.getName()); }
    public static void preserveCalculated(BaseEntity body, BaseEntity existing) {
        for (Field field : CrudService.dataFields(body.getClass())) if (CALCULATED.contains(field.getName())) {
            try {
                Object value = existing == null ? (field.getType() == java.math.BigDecimal.class ? java.math.BigDecimal.ZERO : null) : field.get(existing);
                field.set(body, value);
            } catch (IllegalAccessException ex) { throw new IllegalStateException(ex); }
        }
    }
    public static boolean readOnly(Class<?> cls) { return GENERATED.contains(cls.getSimpleName()); }
    public static boolean readOnly(Class<?> cls, CurrentUser user) {
        return readOnly(cls) || (user.isDemo() && DEMO_SECURITY.contains(cls.getSimpleName()))
                || (cls.getSimpleName().equals("Currency") && !user.hasRole("ADMIN"));
    }
    public static String readOnlyReason(Class<?> cls, CurrentUser user) {
        if (readOnly(cls)) return "Generated by business workflows";
        if (user.isDemo() && DEMO_SECURITY.contains(cls.getSimpleName())) return "Account and company administration is read-only in demo mode";
        if (cls.getSimpleName().equals("Currency") && !user.hasRole("ADMIN")) return "Administrator access is required to change currencies";
        return "";
    }
    public static void access(Class<?> cls, CurrentUser user, boolean write) {
        if (write && user.isDemo() && DEMO_SECURITY.contains(cls.getSimpleName()))
            throw ApiException.forbidden("Account and company administration is read-only in demo mode.");
        if ((ADMIN.contains(cls.getSimpleName()) || (write && cls.getSimpleName().equals("Currency"))) && !user.hasRole("ADMIN"))
            throw ApiException.forbidden("Administrator access is required.");
        if (write && readOnly(cls)) throw ApiException.forbidden("These records are generated by business actions and cannot be edited directly.");
    }
    public static void owned(BaseEntity entity, Long company) {
        if (company == null || !company.equals(entity.companyId)) throw ApiException.notFound("The record was not found in your company.");
    }
    public static void editable(BaseEntity entity) {
        String name = entity.getClass().getSimpleName();
        if (!Set.of("SalInvoice", "SalDelivery", "PurInvoice", "PurGoodsReceipt").contains(name)) return;
        try {
            for (Field field : CrudService.dataFields(entity.getClass()))
                if (field.getName().equals("journalEntryId") && field.get(entity) != null)
                    throw ApiException.conflict("This document has ledger entries and can only be changed by its business workflow.");
            Field field = CrudService.dataFields(entity.getClass()).stream().filter(f -> f.getName().equals("status")).findFirst().orElseThrow();
            String status = String.valueOf(field.get(entity));
            if (name.equals("PurInvoice") && status.equals("APPROVED")) throw ApiException.conflict("An approved invoice can only be changed by its posting workflow.");
            if (Set.of("POSTED", "PAID", "PARTIALLY_PAID", "SHIPPED", "DELIVERED", "RECEIVED", "VOID").contains(status))
                throw ApiException.conflict("This document is already posted. Its business records are locked.");
        } catch (IllegalAccessException ex) { throw new IllegalStateException(ex); }
    }
}
